  r.points_balance,
  coalesce(r.receipt_date, r.created_at, r.updated_at, now()),
  jsonb_build_object(
    'receipt_type', r.receipt_type,
    'refund_for', r.refund_for,
    'cancelled_at', r.cancelled_at,
    'payment_names', array['TC'],
